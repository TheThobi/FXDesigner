/**
 * docs/NODES.md is generated from the generator registry, so the node reference can never
 * drift from the code. After changing a node: `npm run docs` (vitest -u rewrites the file).
 */
import { expect, it } from 'vitest';
import { CATEGORY_LABELS, GENERATOR_FAMILIES } from '../../src/engine/generator';
import type { GeneratorDefinition } from '../../src/engine/generator';
import { glslUniformType } from '../../src/engine/shaderBuilder';
import { GENERATORS } from '../../src/generators/registry';
import type { ParamDef } from '../../src/params/types';
import { numericLimits } from '../../src/params/values';

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function range(d: ParamDef): string {
  switch (d.type) {
    case 'float':
    case 'int': {
      const [lo, hi] = numericLimits(d);
      return `${d.min} … ${d.max}${hi !== d.max || lo !== d.min ? ` (typed: ${lo} … ${hi})` : ''}`;
    }
    case 'select':
      return d.options.map((o) => `${o.value} ${o.label}`).join(', ');
    case 'vec2':
      return `${d.min} … ${d.max} (x, y)`;
    default:
      return '';
  }
}

function value(v: unknown): string {
  if (typeof v === 'string') return v.length > 40 ? `${v.slice(0, 37)}…` : v;
  if (typeof v === 'object' && v !== null && 'stops' in v) return 'ramp';
  return JSON.stringify(v);
}

function nodeSection(g: GeneratorDefinition): string {
  const lines = [`### ${g.name} \`${g.id}\``, '', g.description, ''];
  const kind =
    g.kind === 'simulation'
      ? 'GPU simulation (stateful; not convertible to code)'
      : g.codeParam
        ? `shader with a GLSL code parameter (\`${g.codeParam}\`)`
        : 'shader (`vec4 generate(vec2 uv)`, convertible to code in the editor)';
  lines.push(`- Kind: ${kind}${g.animated ? ', animated (reads `u_time`)' : ''}`);
  if (g.inputs?.length) {
    lines.push(
      `- Inputs: ${g.inputs
        .map(
          (i) =>
            `\`${i.key}\` ${i.label}${i.value ? ` (${i.value})` : ''} — ${i.description} ` +
            `(\`u_in_${i.key}\`, \`u_has_${i.key}\`)`,
        )
        .join('; ')}`,
    );
  }
  if (g.outputs?.length)
    lines.push(`- Outputs: ${g.outputs.map((o) => `\`${o.key}\` ${o.label}`).join(', ')}`);
  if (g.presets?.length) lines.push(`- Presets: ${g.presets.map((p) => p.name).join(', ')}`);
  lines.push('');
  if (g.params.length) {
    lines.push('| Param | Uniform | Type | Range / options | Default | Notes |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const d of g.params) {
      const uniform = g.kind === 'shader' ? glslUniformType(d) : null;
      lines.push(
        `| ${cell(d.label)} \`${d.key}\` | ${uniform ? `\`${uniform} u_${d.key}\`` : '—'} | ${d.type} | ${cell(range(d))} | ${cell(value(d.default))} | ${cell(d.description ?? '')} |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function renderNodeDocs(): string {
  const out = [
    '# Node reference',
    '',
    '<!-- Generated by tests/unit/docs.test.ts from the generator registry: do not edit. -->',
    '<!-- Regenerate with `npm run docs`. -->',
    '',
    `${GENERATORS.length} nodes. Every shader node's GLSL can be shown and edited in the editor`,
    '(Code button of the Generator page); see [AUTHORING.md](AUTHORING.md) to write new ones.',
    'Parameters are uniforms `u_<key>` (float, int for int/select, bool, vec3 for colors,',
    'vec2); ranges are the slider ranges, typed values may go up to the "typed" limits.',
    '',
  ];
  for (const family of GENERATOR_FAMILIES) {
    out.push(`## ${family.label}`, '');
    for (const category of family.categories) {
      const list = GENERATORS.filter((g) => g.category === category);
      if (!list.length) continue;
      if (family.categories.length > 1) out.push(`### — ${CATEGORY_LABELS[category]} —`, '');
      for (const g of list) out.push(nodeSection(g));
    }
  }
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`;
}

it('docs/NODES.md matches the registry (npm run docs to update)', async () => {
  await expect(renderNodeDocs()).toMatchFileSnapshot('../../docs/NODES.md');
});
